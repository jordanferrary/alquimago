import {readFile,mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
const root=process.cwd();
const load=async name=>(await readFile(path.join(root,'src',name),'utf8'));
const clean=code=>code.replace(/\bexport (const|function|async function)\b/g,'$1');
const brain=clean(await load('brain.mjs'));
const config=clean(await load('config.mjs'));
const storage=clean(await load('storage.mjs'));
const project=clean(await load('project.mjs'));
const awareness=clean(await load('awareness.mjs'));
const gestures=clean(await load('gestures.mjs'));
const dialogue=clean(await load('dialogue.mjs'));
const neural=clean(await load('neural.mjs'));
const insight=clean(await load('project-insight.mjs'));
const imageInsight=clean(await load('image-insight.mjs'));
const language=clean(await load('i18n.mjs'));
const skin=clean(await load('skin.mjs'));
const widget=(await load('widget.js')).replace(/^import .*?;\s*$/gm,'');
const bundle=['/* ALQUIMAGO v0.6.0 • MIT */','(() => {','"use strict";',brain,config,storage,project,awareness,gestures,dialogue,neural,insight,imageInsight,language,skin,widget,'})();',''].join('\n');
await mkdir(path.join(root,'dist'),{recursive:true});
await writeFile(path.join(root,'dist/alquimago.js'),bundle);
await writeFile(path.join(root,'dist/alquimago.config.json'),await readFile(path.join(root,'alquimago.config.json'),'utf8'));
console.log('Alquimago: '+(bundle.length/1024).toFixed(1)+' KiB');
